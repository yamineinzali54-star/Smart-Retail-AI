const displayTranslations = new Map<string, string>(
  Object.keys(en).map((key) => [en[key as I18nKey], my[key as I18nKey]] as const),
);
for (const [source, translated] of Object.entries(sharedDisplayTranslations)) {
  displayTranslations.set(source, translated);
}

export function translate(locale: Locale, key: I18nKey): string {
  return dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
}

export function translateDisplayText(locale: Locale, value: string): string {
  return locale === "my" ? displayTranslations.get(value) ?? value : value;
}

export function localizeNode(locale: Locale, node: ReactNode): ReactNode {
  if (typeof node === "string") return translateDisplayText(locale, node);
  if (Array.isArray(node)) return Children.map(node, (child) => localizeNode(locale, child));
  if (isValidElement<{ children?: ReactNode }>(node) && node.props.children !== undefined) {
    return cloneElement(node, {
      children: localizeNode(locale, node.props.children),
    });
  }
  return node;
}

export function detectLocale(): Locale {
  if (typeof document === "undefined") return "en";
  const cookie = document.cookie
    .split(";")
    .map((c) => c.trim())
    .find((c) => c.startsWith(`${LOCALE_COOKIE}=`))
    ?.split("=")[1];
  if (cookie === "my" || cookie === "en") return cookie;
  return (localStorage.getItem(LOCALE_COOKIE) as Locale) === "my" ? "my" : "en";
}

export function persistLocale(locale: Locale): void {
  document.cookie = `${LOCALE_COOKIE}=${locale}; path=/; max-age=31536000`;
  try {
    localStorage.setItem(LOCALE_COOKIE, locale);
  } catch {
    // Private mode — cookie alone is enough.
  }
}

export interface I18nContextValue {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: I18nKey) => string;
}

export const I18nContext = createContext<I18nContextValue>({
  locale: "en",
  setLocale: () => undefined,
  t: (key) => translate("en", key),
});

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
